namespace Spectre.Console;

/// <summary>
/// Represents the display mode for diff rendering.
/// </summary>
public enum DiffMode
{
    /// <summary>
    /// Display diff in inline mode (unified view).
    /// </summary>
    Inline,

    /// <summary>
    /// Display diff in side-by-side mode (split view).
    /// </summary>
    SideBySide,
}
